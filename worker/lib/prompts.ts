export function pickPromptCandidates(random: () => number, count = 3, exclude: Set<string> = new Set()): string[] {
  const pool = PROMPTS.filter((p) => !exclude.has(p));
  const out: string[] = [];
  const used = new Set<number>();
  while (out.length < count && used.size < pool.length) {
    const i = Math.floor(random() * pool.length);
    if (used.has(i)) continue;
    used.add(i);
    out.push(pool[i]!);
  }
  return out;
}
